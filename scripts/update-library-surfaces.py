#!/usr/bin/env python3
"""Keep the authoritative ArkLib modules separate from classic downstream extensions.

The upstream inventory is a reviewed snapshot, not a live network dependency. Update
its revision and file list during an upstream merge. Existing import paths remain
valid; Lake's last matching library owns a module, so the explicit extension globs
below override the broader ArkLib root without weakening its module-system policy.
"""
from __future__ import annotations

import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# BEGIN DOWNSTREAM LIBRARIES (generated by scripts/update-library-surfaces.py)"
END = "# END DOWNSTREAM LIBRARIES"
# Retained source whose direct elaboration exceeds the ordinary build budget.
EXCLUDED = {"ArkLib/ToMathlib/GHSZ02LargeNProof.lean"}


def module_name(path: str) -> str:
    return ".".join("«" + part + "»" if part[0].isdigit() else part
                    for part in Path(path).with_suffix("").parts)


def extension_globs(extensions: set[str], canonical: set[str]) -> list[str]:
    """Compress only subtrees that contain no canonical module."""
    result: list[str] = []

    def walk(prefix: str, extras: set[str], upstream: set[str]) -> None:
        children = {name for name in extras if name.startswith(prefix + ".")}
        if not upstream and children:
            result.append(prefix + (".*" if prefix in extras else ".+"))
            return
        if prefix in extras:
            result.append(prefix)
        next_parts = sorted({name[len(prefix) + 1:].split(".", 1)[0]
                             for name in children})
        for part in next_parts:
            child = prefix + "." + part
            walk(child, {name for name in extras
                         if name == child or name.startswith(child + ".")},
                 {name for name in upstream
                  if name == child or name.startswith(child + ".")})

    walk("ArkLib", extensions, canonical)
    return sorted(result)


def main() -> int:
    tracked = set(subprocess.check_output(
        ["git", "ls-files", "-z", "--", "ArkLib/*.lean"],
        cwd=ROOT).decode().split("\0")) - {""}
    untracked = subprocess.check_output(
        ["git", "ls-files", "--others", "--exclude-standard", "--", "ArkLib/*.lean"],
        cwd=ROOT, text=True).splitlines()
    if untracked:
        raise SystemExit("Stage new Lean files before generating imports:\n" + "\n".join(untracked))
    inventory = json.loads((ROOT / "scripts/arklib-upstream.json").read_text())
    canonical_paths = set(inventory["files"])
    missing = sorted(path for path in canonical_paths if path not in tracked or not (ROOT / path).is_file())
    if missing:
        raise SystemExit("Canonical upstream files are missing:\n" + "\n".join(missing))
    canonical = {module_name(path) for path in canonical_paths}
    extensions = {module_name(path) for path in tracked - canonical_paths - EXCLUDED}
    lines = ["module", ""]
    for module in sorted(canonical):
        lines.extend(["public import", "  " + module] if len(module) + 14 > 100
                     else ["public import " + module])
    (ROOT / "ArkLib.lean").write_text("\n".join(lines) + "\n")

    globs = extension_globs(extensions, canonical)
    # A compressed glob must not pick up a performance-excluded source file.
    excluded = {module_name(path) for path in EXCLUDED}
    if any(any(name == glob.removesuffix(".*").removesuffix(".+") or
                   name.startswith(glob[:-2] + ".") for name in excluded)
           for glob in globs if glob.endswith((".*", ".+"))):
        globs = extension_globs(extensions, canonical | excluded)
    block = "\n".join([
        BEGIN,
        "# Classic downstream modules retain their import paths. The later explicit",
        "# globs own these modules; canonical modules keep ArkLib's module policy.",
        "[[lean_lib]]", 'name = "ArkLibExtensions"', "roots = []",
        "allowNonModules = true", "globs = [",
        *["  " + json.dumps(glob, ensure_ascii=False) + "," for glob in globs],
        "]", "", "[[lean_lib]]", 'name = "ResearchProximityPrize"',
        'roots = ["Research.ProximityPrize"]', "allowNonModules = true", "",
        "[[lean_lib]]", 'name = "ProximityPrizeExtensions"',
        'roots = ["ProximityPrize"]', "allowNonModules = true", END,
    ])
    config_path = ROOT / "lakefile.toml"
    config = config_path.read_text()
    before, sep, rest = config.partition(BEGIN)
    if not sep or END not in rest:
        raise SystemExit("Missing downstream-library markers in lakefile.toml")
    config_path.write_text(before + block + rest.split(END, 1)[1])
    extension_paths = subprocess.check_output(
        ["git", "ls-files", "--", "ProximityPrize/Extensions/*.lean"],
        cwd=ROOT, text=True).splitlines()
    target = ROOT / "ProximityPrize/Extensions.lean"
    target.parent.mkdir(exist_ok=True)
    target.write_text("".join("import " + module_name(path) + "\n"
                              for path in sorted(set(extension_paths))))
    downstream_paths = subprocess.check_output(
        ["git", "ls-files", "--", "ProximityPrize/*.lean"],
        cwd=ROOT, text=True).splitlines()
    other_modules = sorted({module_name(path) for path in downstream_paths
                            if not path.startswith("ProximityPrize/Extensions/")
                            and path != "ProximityPrize/Extensions.lean"})
    (ROOT / "ProximityPrize.lean").write_text("import ProximityPrize.Extensions\n" +
        "".join("import " + module + "\n" for module in other_modules))
    print(f"Generated ArkLib: {len(canonical)} canonical imports; "
          f"ArkLibExtensions: {len(extensions)} modules in {len(globs)} globs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
