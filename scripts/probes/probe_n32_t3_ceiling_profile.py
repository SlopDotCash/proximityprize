"""Exact n=32 t=3 ceiling-maximum profile over all 1024 monomial pencils.

Companion to ``probe_n32_below_ceiling_max.py``.  That probe records the t=3
census of the stack ``(x^3, x^2)`` and shows it is not the t=3 maximum; this
probe computes the full t=3 maximum over all monomial pencils ``(x^a, x^b)``,
``0 <= a, b < 32``, at every prime ``p = 1 (mod 32)`` in ``[97, 20000]``, at
the Fermat prime ``65537`` and at the three prize-scale Proth primes
``k*2^128 + 1``, ``k = 21, 111, 123``.

Object and exact characterisation are those of the companion probe: for a
pencil ``(x^a, x^b)`` the t=3 bad scalars are ``gamma = -D_a(T)/D_b(T)`` over
triples ``T`` with ``D_b(T) != 0``, where ``D_e(T)`` is the 2x2 collinearity
determinant of ``(x, x^e)`` on ``T``.

Findings (all hard-asserted below):

* the scan maximum is 4512, attained only at ``p = 16033``;
* at ``p = 65537`` the maximum is 4640, attained by ``(3,26), (7,30),
  (26,3), (30,7)``;
* at all three prize-scale Proth primes the maximum is 4640, attained by the
  same 56 pencils (listed below); every one has both exponents in ``{2,3}``
  mod 4;
* the t=3 ceiling maximum is therefore not monotone in ``p``, and the
  prize-scale value exceeds every value on the scan.

Independence.  A second implementation recomputes the full 1024-pencil t=3
count table from divided differences
``Q_e(x) = (x^e - x_i^e)/(x - x_i)`` and
``gamma = -(Q_a(x_k)-Q_a(x_j))/(Q_b(x_k)-Q_b(x_j))``, with no collinearity
determinants, and must agree exactly at the four large primes.  A literal
line-witness routine (triple Cramer candidates plus a full-line audit of the
MCA event) recomputes every listed maximizer at ``p = 65537`` and at the
prize-scale prime ``k = 21``.

Scope: finite fields only, ``n = 32``, monomial pencils only.  This is finite
data, not a field-uniform theorem, not a maximum over all stacks, not a
production ``n = 2^30/2^32`` statement, and not a claim about ``delta*`` or
the prize.  The exponent-class observation is a description of the listed
set, not a proved classification law.
"""

