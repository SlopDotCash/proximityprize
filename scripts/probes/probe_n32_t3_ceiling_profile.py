def t3_counts(p, n=N):
    """Exact t=3 bad-scalar counts for all pencils, determinant path."""
    xs, determinants, inverses, _ = base.build(p, n)
    counts = {}
    for a in range(n):
        first = determinants[a]
        for b in range(n):
            if b < 2:
                counts[(a, b)] = 0
                continue
            second = determinants[b]
            second_inverse = inverses[b]
            bad = set()
            for index, db in enumerate(second):
                if db:
                    bad.add((-first[index] * second_inverse[index]) % p)
            counts[(a, b)] = len(bad)
    return xs, counts


def t3_counts_divided(p, n=N):
    """Second implementation: divided differences, no 2x2 determinants."""
    generator = base.order_element(p, n)
    xs = [pow(generator, exponent, p) for exponent in range(n)]
    powers = [[pow(x, exponent, p) for x in xs] for exponent in range(n)]
    inverse_difference = [[0] * n for _ in range(n)]
    for i in range(n):
        for r in range(n):
            if i != r:
                inverse_difference[i][r] = pow((xs[r] - xs[i]) % p, -1, p)
    triples = list(combinations(range(n), 3))
    divided = []
    for exponent in range(n):
        row_values = powers[exponent]
        row = []
        for i, j, k in triples:
            qj = (row_values[j] - row_values[i]) * inverse_difference[i][j] % p
            qk = (row_values[k] - row_values[i]) * inverse_difference[i][k] % p
            row.append((qk - qj) % p)
        divided.append(row)
    counts = {}
    for a in range(n):
        first = divided[a]
        for b in range(n):
            if b < 2:
                counts[(a, b)] = 0
                continue
            second = divided[b]
            nonzero = [index for index, value in enumerate(second) if value]
            inverses = base.batch_inverse([second[index] for index in nonzero], p)
            bad = {(-first[index] * inverse) % p for index, inverse in zip(nonzero, inverses)}
            counts[(a, b)] = len(bad)
    return counts


def affine_test(values, points, xs, p):
    if len(points) <= 2:
        return True
    i, j = points[0], points[1]
    dx = (xs[j] - xs[i]) % p
    dy = (values[j] - values[i]) % p
    for index in points[2:]:
        if (dx * (values[index] - values[i]) - (xs[index] - xs[i]) * dy) % p:
            return False
    return True


def bad_set_lines(n, xs, u0, u1, threshold, p):
    """Literal line-witness algorithm: Cramer candidates, full-line audit."""
    pair_inverse = {
        (i, j): pow((xs[j] - xs[i]) % p, -1, p) for i, j in combinations(range(n), 2)
    }
    candidates = set()
    for i, j, k in combinations(range(n), 3):
        a11 = (u1[j] - u1[i]) % p
        a12 = (xs[i] - xs[j]) % p
        a21 = (u1[k] - u1[i]) % p
        a22 = (xs[i] - xs[k]) % p
        determinant = (a11 * a22 - a12 * a21) % p
        if not determinant:
            continue
        b1 = (u0[j] - u0[i]) % p
        b2 = (u0[k] - u0[i]) % p
        gamma = ((-b1) * a22 - a12 * (-b2)) * pow(determinant, -1, p) % p
        candidates.add(gamma)
    bad = set()
    for gamma in candidates:
        pencil = [(u0[index] + gamma * u1[index]) % p for index in range(n)]
        lines = {}
        for i, j in combinations(range(n), 2):
            slope = (pencil[j] - pencil[i]) * pair_inverse[(i, j)] % p
            intercept = (pencil[i] - slope * xs[i]) % p
            lines.setdefault((slope, intercept), []).append(i)
        for (slope, intercept), indices in lines.items():
            if len(indices) < threshold:
                continue
            witness = [
                index for index in range(n)
                if (intercept + slope * xs[index] - pencil[index]) % p == 0
            ]
            if len(witness) < threshold:
                continue
            if not (affine_test(u0, witness, xs, p) and affine_test(u1, witness, xs, p)):
                bad.add(gamma)
                break
    return bad


def summarize(counts):
    maximum = max(counts.values())
    return maximum, tuple(sorted(pair for pair, value in counts.items() if value == maximum))


def main():
    print("n=32 t=3 ceiling-maximum profile over all 1024 monomial pencils")
    primes = base.primes_one_mod(32, LIMIT)
    assert len(primes) == 146, len(primes)
    profile = {}
    by_value = {}
    for index, p in enumerate(primes):
        _, counts = t3_counts(p)
        maximum, _ = summarize(counts)
        profile[p] = maximum
        by_value.setdefault(maximum, []).append(p)
        if index % 50 == 0:
            print(f"  scanned {index + 1}/{len(primes)} (last p={p})", flush=True)
    assert profile == T3_PROFILE, "t=3 profile changed"
    scan_top = max(by_value)
    assert scan_top == 4512 and by_value[scan_top] == [16033], (scan_top, by_value[scan_top])
    print(f"scan: 146 primes, t=3 maximum {scan_top}, only at p=16033")
    print(f"primes at the previous value 4416: {by_value[4416]}")

    p = 65537
    _, counts = t3_counts(p)
    top, winners = summarize(counts)
    assert (top, winners) == (4640, T3_65537), (top, winners)
    assert counts[(3, 2)] == 3264, counts[(3, 2)]
    print(f"p=65537: t=3 max {top} at {winners}; (x^3,x^2) count 3264")

    prize_sets = []
    for k, witness in ((21, 5), (111, 5), (123, 7)):
        p = k * (2 ** 128) + 1
        assert pow(witness, (p - 1) // 2, p) == p - 1, (k, witness)
        _, counts = t3_counts(p)
        top, winners = summarize(counts)
        assert top == 4640 and len(winners) == 56, (k, top, len(winners))
        assert counts[(3, 2)] == 4512, counts[(3, 2)]
        prize_sets.append(winners)
        print(f"k={k} prize-scale Proth prime (witness {witness}): t=3 max {top}, "
              f"{len(winners)} maximizers, (x^3,x^2) count 4512")
    assert prize_sets[0] == prize_sets[1] == prize_sets[2] == PRIZE_T3_MAXIMIZERS
    assert all(a % 4 in (2, 3) and b % 4 in (2, 3) and a % 4 != b % 4
               for a, b in PRIZE_T3_MAXIMIZERS)
    print("  the 56 prize-scale maximizers are identical at k=21,111,123")

    for k in (21, 111, 123):
        p = k * (2 ** 128) + 1
        _, fast = t3_counts(p)
        slow = t3_counts_divided(p)
        assert fast == slow, ("divided-difference mismatch", k)
    _, fast = t3_counts(65537)
    assert fast == t3_counts_divided(65537), "divided-difference mismatch at 65537"
    print("independent divided-difference table agrees at p=65537 and k=21,111,123")

    p = 65537
    xs = [pow(base.order_element(p, N), exponent, p) for exponent in range(N)]
    for a, b in T3_65537:
        u0 = [pow(x, a, p) for x in xs]
        u1 = [pow(x, b, p) for x in xs]
        assert len(bad_set_lines(N, xs, u0, u1, 3, p)) == 4640, (a, b)
    print("line-witness audit: all four p=65537 maximizers have 4640 bad scalars")

    p = 21 * (2 ** 128) + 1
    xs = [pow(base.order_element(p, N), exponent, p) for exponent in range(N)]
    for a, b in PRIZE_T3_MAXIMIZERS:
        u0 = [pow(x, a, p) for x in xs]
        u1 = [pow(x, b, p) for x in xs]
        assert len(bad_set_lines(N, xs, u0, u1, 3, p)) == 4640, (a, b)
    print("line-witness audit: all 56 prize-scale maximizers have 4640 bad scalars")

    print("PASS: t=3 profile over 146 primes, 65537 and three prize-scale primes; "
          "independent divided-difference tables and line-witness maximizers agree")


if __name__ == "__main__":
    main()
