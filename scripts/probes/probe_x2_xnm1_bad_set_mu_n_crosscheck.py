#!/usr/bin/env python3
"""Independent crosscheck of the (x^2, x^(n-1)) closed form: bad-scalar set is mu_n.

Four routes, none of which uses the coset-key engine of the main probe:

* Route A (literal triples, set equality).  For every literal triple ``T`` of ``mu_n``
  the two collinearity determinants ``D_2(T)`` and ``D_(n-1)(T)`` are computed with the
  raw 2x2 elimination determinant on the actual field values -- no shape normalisation,
  no ``h`` closed form, no ``V_T`` factor.  The bad set is collected literally as
  ``{ -D_2(T)/D_(n-1)(T) : D_(n-1)(T) != 0 }`` and compared as a SET with ``mu_n``,
  so it also proves the reverse inclusion (every domain element is bad), not just a size.
* Route B (discrete logs at the Fermat prime).  A full base-primitive-root logarithm
  table of ``F_65537`` replaces every modular exponentiation key of the main probe by an
  integer index computation in ``Z/65536``: membership in ``mu_n`` is ``log`` divisible
  by ``(p-1)/n``, and the dilation orbit is the coset of the subgroup generated by
  ``(a-b)*(p-1)/n``.  The index set of the bad set is compared with ``<w^((p-1)/n)>``.
* Route C (identity by exact polynomial division).  The five group-ring identities of the
  main probe are re-derived over ``Z[y, z]`` with UNREDUCED exponents by dividing by
  ``y^n - 1`` in ``(Z[z])[y]`` and then by ``z^n - 1`` in ``(Z[y])[z]``, and the resulting
  ideal-membership certificate ``Q1*(y^n-1) + Q2*(z^n-1)`` is re-expanded by plain
  integer polynomial multiplication and compared term by term with the difference.  This
  is a different algorithm from the exponent-folding group ring, and ``h_(-2) = h_(-1) =
  0``, ``h_0 = 1``, ``h_1 = 1 + y + z`` come out with zero remainder, i.e. as identities
  in ``Z[y, z]`` that need no root-of-unity hypothesis at all.
* Route D (merged integers by the negated-3-sum route).  The ``(x^3, x^2)`` ceiling count
  that the main probe takes as its merged anchor is recomputed as the literal set of
  negated triple sums of ``mu_16`` (the semantics of the merged PR #267 probe) and
  compared cell by cell with the shape engine.

Stdlib only, deterministic, integer arithmetic only.  It checks the same objects as the
main probe at the same parameters and agrees on every integer printed there; it adds no
claim of its own.  Same scope limits as the main probe: ``t = 3`` ceiling monomial-pencil
census on smooth domains ``mu_n``, ``n = 2^k``, finite fields only -- no ``t >= 4``, no
global maximum, no production regime, no ``delta*``, no prize statement.
"""

import time
from itertools import combinations
from math import gcd, isqrt

FERMAT = 65537
PRIZE_EXP = 128
LADDER = (8, 16, 32, 64, 128, 256, 512, 1024)
LITERAL_RUNGS = (8, 16, 32, 64)
LIMIT = 20_000

# Merged PR #267 anchor values used by Route D.  This is the complete published
# 34-prime CEILING_EXCEPTIONS table of scripts/probes/probe_n16_below_ceiling_max.py,
# transcribed unchanged.
MERGED_N16 = {17: 17, 97: 96, 113: 112, 193: 192, 241: 240, 257: 224, 337: 272,
              353: 272, 401: 320, 433: 352, 449: 336, 577: 304, 593: 416, 641: 368,
              673: 416, 769: 416, 881: 416, 929: 416, 977: 416, 1153: 448,
              1217: 448, 1249: 448, 1297: 416, 1361: 416, 1409: 416, 1489: 416,
              1777: 448, 2129: 448, 2273: 448, 2689: 448, 2833: 448, 3089: 448,
              4001: 448, 4049: 448}
# Published anchors outside the [17, LIMIT] scan range, computed separately.
MERGED_N16_OUTSIDE = {65537: 464}
N512_65537_CELL = 512


def is_prime(value):
    if value < 2:
        return False
    if value % 2 == 0:
        return value == 2
    divisor = 3
    while divisor * divisor <= value:
        if value % divisor == 0:
            return False
        divisor += 2
    return True


def primes_one_mod(p_mod, limit):
    sieve = bytearray(b"\x01") * (limit + 1)
    sieve[:2] = b"\x00\x00"
    for divisor in range(2, isqrt(limit) + 1):
        if sieve[divisor]:
            start = divisor * divisor
            sieve[start:limit + 1:divisor] = b"\x00" * len(sieve[start:limit + 1:divisor])
    return [p for p in range(p_mod, limit + 1) if sieve[p] and p % p_mod == 1]


def proth_prime(k, exponent):
    value = k * (2 ** exponent) + 1
    assert k % 2 == 1 and k < 2 ** exponent, (k, exponent)
    for witness in range(2, 64):
        if pow(witness, (value - 1) // 2, value) == value - 1:
            return value, witness
    raise AssertionError(f"no Proth witness below 64 for k={k}")


def order_element(p, n):
    for candidate in range(2, p):
        generator = pow(candidate, (p - 1) // n, p)
        if pow(generator, n // 2, p) == p - 1:
            assert pow(generator, n, p) == 1
            return generator
    raise AssertionError(f"no element of order {n} modulo {p}")


def primitive_root(p):
    order = p - 1
    factors = []
    remaining = order
    divisor = 2
    while divisor * divisor <= remaining:
        if remaining % divisor == 0:
            factors.append(divisor)
            while remaining % divisor == 0:
                remaining //= divisor
        divisor += 1
    if remaining > 1:
        factors.append(remaining)
    for candidate in range(2, p):
        if all(pow(candidate, order // factor, p) != 1 for factor in factors):
            return candidate
    raise AssertionError(f"no primitive root modulo {p}")


def log_table(p):
    """Discrete logs base primitive_root(p) for every element of F_p^*."""
    root = primitive_root(p)
    table = {1: 0}
    value = 1
    for index in range(1, p - 1):
        value = value * root % p
        assert value not in table
        table[value] = index
    assert len(table) == p - 1
    assert value * root % p == 1          # root^(p-1) = 1, table covers F_p^*
    return root, table


# ---------------------------------------------------------------------------
# Route A: literal triples, raw determinants, exact set equality with mu_n.
# ---------------------------------------------------------------------------

def literal_triples(n):
    return n * (n - 1) * (n - 2) // 6


def literal_bad_set(n, p, first=2, second=None):
    second = n - 1 if second is None else second
    generator = order_element(p, n)
    xs = [pow(generator, exponent, p) for exponent in range(n)]
    assert len(set(xs)) == n
    u_first = [pow(x, first, p) for x in xs]
    u_second = [pow(x, second, p) for x in xs]
    bad = set()
    denominator_nonzero = 0
    jointly_affine = 0
    for i, j, k in combinations(range(n), 3):
        a11 = (u_second[j] - u_second[i]) % p
        a12 = (xs[i] - xs[j]) % p
        a21 = (u_second[k] - u_second[i]) % p
        a22 = (xs[i] - xs[k]) % p
        det_second = (a11 * a22 - a12 * a21) % p
        b1 = (u_first[j] - u_first[i]) % p
        b2 = (u_first[k] - u_first[i]) % p
        det_first = (b1 * a22 - a12 * b2) % p
        if det_second:
            denominator_nonzero += 1
            bad.add((((-b1) * a22 - a12 * (-b2)) % p) * pow(det_second, -1, p) % p)
        elif not det_first:
            jointly_affine += 1
    return xs, bad, denominator_nonzero, jointly_affine, literal_triples(n)


def route_a():
    total = 0
    for n in LITERAL_RUNGS:
        primes = [FERMAT]
        if n <= 32:
            primes = primes_one_mod(n, 400)[:2] + [FERMAT]
        prize, _ = proth_prime(21, PRIZE_EXP)
        for p in primes + [prize]:
            xs, bad, denom_nonzero, jointly, triples = literal_bad_set(n, p)
            assert bad == set(xs), (n, p, len(bad), len(xs))
            assert len(bad) == n, (n, p, len(bad))
            assert 0 not in bad, (n, p)
            assert jointly == 0, (n, p, jointly)
            assert denom_nonzero == triples, (n, p, denom_nonzero, triples)
            total += 1
            print(f"  route A n={n} p={'prize 21*2^128+1' if p > 1000000 else p}: "
                  f"all {triples} literal triples contribute (D_(n-1) never vanishes), "
                  f"bad set == mu_{n} as a SET, |bad| = {len(bad)}", flush=True)
    # the n=512 a=2 row cell, enumerated literally over all of mu_512
    prize, _ = proth_prime(21, PRIZE_EXP)
    for p in (FERMAT,):
        xs, bad, denom_nonzero, jointly, triples = literal_bad_set(512, p)
        assert bad == set(xs) and len(bad) == N512_65537_CELL, (p, len(bad))
        assert denom_nonzero == triples and jointly == 0
        print(f"  route A n=512 p={p}: all {triples} literal triples of mu_512 enumerated, "
              f"D_511 nonzero everywhere, bad set == mu_512, count {len(bad)} (the "
              f"n=512 a=2 row deficit cell of the census)", flush=True)
    return total


# ---------------------------------------------------------------------------
# Route B: discrete-log indices at the Fermat prime.
# ---------------------------------------------------------------------------

def det_col(ts, exponent, p):
    """The literal collinearity determinant D_exponent of (1, x, x^exponent) on ts."""
    t0, t1, t2 = ts
    return ((t1 - t0) * (pow(t2, exponent, p) - pow(t0, exponent, p))
            - (t2 - t0) * (pow(t1, exponent, p) - pow(t0, exponent, p))) % p


def route_b():
    root, logs = log_table(FERMAT)
    assert pow(root, FERMAT - 1, FERMAT) == 1 and logs[1] == 0
    cells = 0
    for n in LADDER:
        step = (FERMAT - 1) // n            # mu_n = <root^step>
        generator = pow(root, step, FERMAT)
        assert pow(generator, n, FERMAT) == 1 and len({pow(generator, i, FERMAT)
                                                      for i in range(n)}) == n
        indices = set()
        shapes = 0
        for u in range(1, n):
            y = pow(generator, u, FERMAT)
            for v in range(u + 1, n):
                z = pow(generator, v, FERMAT)
                shapes += 1
                det2 = det_col((1, y, z), 2, FERMAT)
                detn = det_col((1, y, z), n - 1, FERMAT)
                assert det2 and detn, (n, u, v)
                ratio = (-det2 * pow(detn, -1, FERMAT)) % FERMAT
                index = logs[ratio]
                assert index % step == 0, (n, ratio, index, step)
                indices.add(index // step % n)
        assert gcd(3 - n, n) == 1, n
        assert shapes == (n - 1) * (n - 2) // 2, (n, shapes)
        assert indices == set(range(n)), (n, len(indices))
        cells += 1
        print(f"  route B n={n} p={FERMAT}: all {shapes} shape ratios of the pencil "
              f"(x^2, x^{n - 1}) have log base {root} divisible by (p-1)/n = {step}, and "
              f"the {len(indices)} quotients log/step are exactly {{0..{n - 1}}}: the bad "
              f"set is mu_{n} itself, so the count is n (no modular-exponent key used)",
              flush=True)
    return cells


# ---------------------------------------------------------------------------
# Route C: exact ideal-membership certificates over Z[y, z], unreduced exponents.
# ---------------------------------------------------------------------------

def poly_mul(a, b):
    out = {}
    for (ay, az), ac in a.items():
        for (by, bz), bc in b.items():
            key = (ay + by, az + bz)
            out[key] = out.get(key, 0) + ac * bc
    return {k: v for k, v in out.items() if v}


def poly_add(*terms):
    out = {}
    for term in terms:
        for key, coeff in term.items():
            out[key] = out.get(key, 0) + coeff
    return {k: v for k, v in out.items() if v}


def poly_sub(a, b):
    return poly_add(a, {key: -coeff for key, coeff in b.items()})


def divide_by(poly, power, axis):
    """Divide a Z[y, z] polynomial by (y^power - 1) or (z^power - 1), exactly.

    Returns (quotient, remainder) with the remainder free of exponents >= power on that
    axis.  Plain long division with integer coefficients: no exponent folding, no
    modular arithmetic, no floats.
    """
    quotient = {}
    rest = dict(poly)
    while True:
        high = [(key, coeff) for key, coeff in rest.items() if key[axis] >= power]
        if not high:
            break
        (top), coeff = max(high, key=lambda item: item[0])
        ey, ez = top
        qkey = (ey - power, ez) if axis == 0 else (ey, ez - power)
        quotient[qkey] = quotient.get(qkey, 0) + coeff
        del rest[top]
        rest[qkey] = rest.get(qkey, 0) + coeff
        if not rest[qkey]:
            del rest[qkey]
    return {k: v for k, v in quotient.items() if v}, {k: v for k, v in rest.items() if v}


def unreduced_numerator(exponent):
    """N_e = (y - z) + y^e (z - 1) + z^e (1 - y) with exponents kept unreduced."""
    y = {(1, 0): 1}
    z = {(0, 1): 1}
    one = {(0, 0): 1}
    ye = {(exponent, 0): 1}
    ze = {(0, exponent): 1}
    return poly_add(poly_sub(y, z),
                    poly_mul(ye, poly_sub(z, one)),
                    poly_mul(ze, poly_sub(one, y)))


def unreduced_denominator():
    y = {(1, 0): 1}
    z = {(0, 1): 1}
    one = {(0, 0): 1}
    return poly_mul(poly_mul(poly_sub(one, y), poly_sub(one, z)), poly_sub(y, z))


def certificate(n):
    """The multiplier identity as an exact ideal-membership certificate in Z[y, z]."""
    y = {(1, 0): 1}
    z = {(0, 1): 1}
    one = {(0, 0): 1}
    denom = unreduced_denominator()
    exact = {
        "N_0 == 0": unreduced_numerator(0),
        "N_1 == 0": unreduced_numerator(1),
        "N_2 - denom": poly_sub(unreduced_numerator(2), denom),
        "N_3 - denom*(1+y+z)": poly_sub(unreduced_numerator(3),
                                       poly_mul(denom, poly_add(one, y, z))),
    }
    for label, poly in exact.items():
        assert poly == {}, (n, label, sorted(poly.items())[:4])
    delta = poly_sub(poly_mul(poly_mul(y, z), unreduced_numerator(n - 1)), denom)
    quotient_y, remainder = divide_by(delta, n, 0)
    quotient_z, remainder_z = divide_by(remainder, n, 1)
    assert remainder_z == {}, (n, sorted(remainder_z.items())[:4])
    rebuilt = poly_add(poly_mul(quotient_y, {(n, 0): 1, (0, 0): -1}),
                       poly_mul(quotient_z, {(0, n): 1, (0, 0): -1}))
    assert rebuilt == delta, (n, "certificate re-expansion mismatch")
    return {"exact": exact, "delta": delta, "quotient_y": quotient_y,
            "quotient_z": quotient_z}


# ---------------------------------------------------------------------------
# Route D: merged n=16 anchor through the negated-triple-sum semantics.
# ---------------------------------------------------------------------------

def triple_sum_count(n, p):
    generator = order_element(p, n)
    xs = [pow(generator, exponent, p) for exponent in range(n)]
    sums = {(-(xs[i] + xs[j] + xs[k])) % p for i, j, k in combinations(range(n), 3)}
    return len(sums), sums


def main():
    start = time.time()
    prize, witness = proth_prime(21, PRIZE_EXP)
    print(f"p = {FERMAT} prime, primitive root available; prize Proth prime "
          f"21*2^128+1 certified with witness a={witness}", flush=True)

    cells_a = route_a()
    cells_b = route_b()

    for n in LADDER:
        proof = certificate(n)
        print(f"  route C n={n}: h_(-2)=h_(-1)=0, h_0=1 and h_1=1+y+z are exact "
              f"identities in Z[y, z] (remainder zero without any root-of-unity "
              f"hypothesis); y*z*N_(n-1) - denom = Q1*(y^n-1) + Q2*(z^n-1) with "
              f"{len(proof['quotient_y'])} + {len(proof['quotient_z'])} quotient terms, "
              f"remainder 0, certificate re-expanded and matched term by term "
              f"({len(proof['delta'])} terms in the difference)", flush=True)

    sixteen = primes_one_mod(16, LIMIT)
    profile = {p: triple_sum_count(16, p)[0] for p in sixteen}
    cells_d = 0
    table = []
    for p, expected in sorted(MERGED_N16.items()):
        assert p in profile, ("published anchor prime outside the scan", p)
        assert profile[p] == expected, (p, profile[p], expected)
        table.append((p, profile[p]))
        cells_d += 1
    outside = []
    for p, expected in sorted(MERGED_N16_OUTSIDE.items()):
        count, _ = triple_sum_count(16, p)
        assert count == expected, (p, count, expected)
        outside.append((p, count))
    computed = sorted((p, c) for p, c in profile.items() if c != 464)
    assert computed == sorted(table), ("exception set differs", computed, sorted(table))
    print(f"route D: the merged PR #267 n=16 (x^3,x^2) ceiling integers are reproduced "
          f"entry by entry by the literal negated triple-sum set at every one of the "
          f"{cells_d} published exception primes "
          f"{table}; scanning all {len(sixteen)} primes p = 1 (mod 16) in [17, {LIMIT}] "
          f"the computed exception set EQUALS that published table as a set "
          f"({len(computed)} entries), with {len(sixteen) - len(computed)} primes at 464; "
          f"outside the scan range {outside} at the primes of "
          f"{sorted(MERGED_N16_OUTSIDE)} (shape engine agrees on the same cells "
          f"in the main probe)", flush=True)
    n8_primes = primes_one_mod(8, LIMIT)
    split = []
    for p in n8_primes:
        count, _ = triple_sum_count(8, p)
        if count != 40:
            split.append((p, count))
    assert split == [(17, 16)], split
    print(f"route D: n=8 negated triple sums over all {len(n8_primes)} primes "
          f"p = 1 (mod 8) in [17, {LIMIT}] give 40 everywhere except {split} "
          f"(G310/G328/G330 boundary)", flush=True)

    print(f"PASS: independent routes agree -- literal-triple set equality at "
          f"{cells_a} cells, discrete-log index sets at {cells_b} cells, exact "
          f"polynomial certificates at {len(LADDER)} rungs, merged anchors at "
          f"{len(n8_primes) + len(sixteen) + len(outside)} distinct (n, p) cells "
          f"({len(n8_primes)} at n=8, {len(sixteen)} at n=16 inside the scan range, "
          f"{len(outside)} at n=16 outside it); every count is n, matching the main probe "
          f"cell for cell", flush=True)
    print(f"elapsed {time.time() - start:.1f}s", flush=True)


if __name__ == "__main__":
    main()
