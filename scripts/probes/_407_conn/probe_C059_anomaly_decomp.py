def Er_char0_via_Zzeta(mu_exponents, n, r):
    """E_r^{char0} = R_r(0) over Z[zeta_n]: number of (x,y) in mu_n^{2r} with sum x = sum y
       as elements of Z[zeta_n] = Z[x]/Phi_n(x).  We compute the r-fold sum distribution
       as a Counter over the canonical Z[zeta_n] coordinate vector (reduced mod Phi_n), then
       R_r(0) = sum over states of (count_in_sumr)^2  (the diagonal autocorrelation).
       mu_exponents: list of exponents e (0..n-1) so that root = zeta_n^e ; here mu_n = ALL n-th
       roots so exponents = range(n)."""
    import numpy as np
    # cyclotomic Phi_n for n = 2^mu (mu>=1): Phi_n(x) = x^{n/2} + 1 ; basis = {1,x,...,x^{n/2 -1}}
    # zeta_n^e reduces: for e < n/2 -> +x^e ; for n/2 <= e < n -> -x^{e-n/2}
    half = n//2
    def coord(e):
        e %= n
        v = [0]*half
        if e < half:
            v[e] += 1
        else:
            v[e-half] -= 1
        return tuple(v)
    # single-element distribution over coordinate vectors
    f = Counter()
    for e in mu_exponents:
        f[coord(e)] += 1
    def add_coord(a, b):
        return tuple(x+y for x,y in zip(a,b))
    def conv(a, b):
        c = Counter()
        for x, ax in a.items():
            for y, by in b.items():
                c[add_coord(x,y)] += ax*by
        return c
    sumr = Counter({tuple([0]*half):1})
    for _ in range(r):
        sumr = conv(sumr, f)
    # R_r(0) over Z[zeta_n] = sum_s sumr(s)^2  (number of (x,y) with sum x = sum y)
    E0 = sum(cnt*cnt for cnt in sumr.values())
    return E0, sumr

def run(n, beta, r):
    q = find_prize_prime(n, beta)
    if q is None:
        print(f"  n={n} beta={beta}: no prime found"); return
