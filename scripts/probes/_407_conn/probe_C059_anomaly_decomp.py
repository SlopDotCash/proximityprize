    cap_max_offdiag = max((v for z,v in R.items() if z!=0), default=0)
    # (C) USEFULNESS: C059 upper bound = R0 * (#contributing cosets).
    # contributing cosets = distinct nonzero F_q-values among diff states that are p|z... but
    # the anomaly lands at z=0 in F_q. The "contributing sublattice points" are the cyclotomic
    # states s != 0 with to_Fq(s)=0. Their count:
    num_contrib_states = contributing_states
    # The bound as literally stated in C059 (#{z!=0,p|z in 2r-box} * R_r(0)) -- the count of
    # nonzero F_q residues z that are "p|z" is ZERO mod a prime (only z=0 is divisible by p in F_q!).
    # So the literal F_q reading is degenerate. The MEANINGFUL reading is the cyclotomic one above:
