from collections import Counter

def is_prime(m):
    if m < 2: return False
    if m % 2 == 0: return m == 2
    i = 3
    while i*i <= m:
        if m % i == 0: return False
        i += 2
    return True

def find_prize_prime(n, beta, tries=200000):
    """smallest prime q ~ n^beta with q == 1 mod n (so mu_n exists), n << sqrt(q)."""
    target = int(round(n**beta))
    # walk to q = 1 mod n above target
    base = target - (target % n) + 1
    if base <= target: base += n
    q = base
    for _ in range(tries):
        if is_prime(q):
            return q
        q += n
    return None

def subgroup_mu_n(q, n):
    """the order-n multiplicative subgroup mu_n of F_q^*  (q prime). returns sorted list of ints in [1,q-1]."""
    # find a generator-power: pick any g, raise to (q-1)/n
    e = (q-1)//n
    # find primitive-ish: just collect powers of some element of order n
    for cand in range(2, q):
        h = pow(cand, e, q)
        if h == 1:
            continue
        # order of h divides n; check it's exactly n
        S = set()
        x = 1
        for _ in range(n):
            x = (x*h) % q
            S.add(x)
        if len(S) == n:
            return sorted(S)
    raise RuntimeError("no mu_n found")

def Rr_charp(mu, q, r):
    """R_r(z) for all z in F_q : number of (x_1..x_r,y_1..y_r) in mu^{2r} with sum x - sum y = z mod q.
       Computed via DFT-free convolution of the r-fold signed-sum distribution.
       Returns Counter z -> count.  E_r^{Fp} = R_r(0)."""
    # r-fold sum distribution of mu (additive in F_q)
    # f1 = distribution of single element
    f = Counter()
    for a in mu: f[a % q] += 1
    # convolve r times to get sum of r elements
    def conv(a, b):
        c = Counter()
        for x, ax in a.items():
            for y, by in b.items():
                c[(x+y) % q] += ax*by
        return c
    sumr = Counter({0:1})
    for _ in range(r):
        sumr = conv(sumr, f)
    # negated sum distribution
    negr = Counter()
    for s, cnt in sumr.items():
        negr[(-s) % q] += cnt
    # R_r = sumr (*) negr  : R_r(z) = sum_s sumr(s) negr(z-s)
    R = conv(sumr, negr)
    return R

