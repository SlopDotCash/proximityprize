    anomaly = Erp - E0
    R0 = Erp                         # autocorr at origin in char p
    # (A) IDENTITY: anomaly == sum_{z != 0} R_r(z)  ... but careful: in F_q the "char0" energy
    # is the z=0 mass MINUS the wraparound collisions that ALSO land at z=0. The proper anomaly
    # decomposition (C059) is: extra char-p collisions at z=0 come from nonzero cyclotomic-integer
    # differences alpha with p | N(alpha), i.e. alpha != 0 in Z[zeta_n] but ==0 in F_q.
    # So: anomaly = #{(x,y): sum x - sum y = 0 in F_q  AND  != 0 in Z[zeta_n]}.
    # That equals sum over nonzero cyclotomic states s of [count of (x,y) pairs giving difference s
    # whose F_q-image is 0].  We compute it DIRECTLY for cross-check.
    # difference distribution over Z[zeta_n]:
    # diff = sumr0 (*) (-sumr0)
    half = n//2
    def neg(v): return tuple(-x for x in v)
    diff = Counter()
