"""Generate kernel-checkable tables for the 64-root two-anchor list certificate."""

from functools import cache
from pathlib import Path


RADIX = 2**64
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "ArkLib/Research/ProximityGap/Frontier/QuotientSignatureTables.lean"


def tree(v, w=None):
    if len(v) == 1:
        return v[0], None if w is None else w[0]
    half = len(v) // 2
    return (tree(v[:half], w if w is None else w[:half]),
            tree(v[half:], w if w is None else w[half:]))


def leaf(node):
    return isinstance(node[0], int)


@cache
def packed(node, x, y):
    if leaf(node):
        v, w = node
        return int(x == v and (w is None or y == w))
    left, right = node
    return sum(c * d * RADIX**(a+b) * packed(left, x+a, y+b) * packed(right, x+b, y+a)
               for a, c in enumerate((1, 2, 1)) for b, d in enumerate((1, 2, 1)))


def main():
    out = ["""/-
Copyright (c) 2026 Proximity Prize Contributors. All rights reserved.
SPDX-License-Identifier: MIT OR Apache-2.0
-/
import ArkLib.Research.ProximityGap.Frontier.QuotientSignatureCensus

/-! # Certified 64-root signature populations

Generated by scripts/probes/generate_quotient_signature_tables.py. Each table
is checked against the two smaller tables in the exact recurrence. The radix
digit at position 33 counts actual selections of 33 sites.
-/

namespace ProximityGap.QuotientSignatureTables
open QuotientSignatureCensus
-- Several individual radix-packed table entries exceed one hundred decimal places.
set_option linter.style.longLine false
set_option maxRecDepth 6000
set_option maxHeartbeats 0
private abbrev radix : ℕ := 2^64
"""]
    labels = {}

    def certificate(node, radius):
        key = (node, radius)
        if key in labels:
            return labels[key]
        if leaf(node):
            v, w = node
            option = "none" if w is None else f"(some {w})"
            desc = f".leaf {v} {option}"
            proof = f"leaf_correct radix {v} {option} {radius}"
        else:
            left = certificate(node[0], radius + 2)
            right = certificate(node[1], radius + 2)
            desc = f".fork s{left} s{right}"
            proof = f"fork_correct radix s{left} s{right} {radius} t{left} t{right}"
        i = len(labels)
        labels[key] = i
        rows = [", ".join(str(packed(node, x, y)) for y in range(radius+1))
                for x in range(radius+1)]
        out.extend([f"private abbrev s{i} : Tree := {desc}",
                    f"private def t{i} : Array ℕ := #[",
                    ",\n".join("  " + row for row in rows) + "]"])
        prior = "" if leaf(node) else f" h{left} h{right}"
        out.append(f"private theorem h{i} : Correct radix s{i} {radius} t{i} :=\n"
                   f"  {proof} t{i}{prior} (by decide +kernel)\n")
        return i

    patterns = {"A": [5]*16, "B": [6]*8 + [5]*8,
                "C": [5]*8 + [6]*8, "D": [5]*12 + [6]*4}
    targets = [(f"single{name}", v, None) for name, v in patterns.items()]
    targets += [(f"joint{x}{y}", v, w) for x, v in patterns.items() if x != "D"
                for y, w in patterns.items()]
    public = []
    for name, v, w in targets:
        node = tree(v, w)
        i = certificate(node, 2)
        total = sum(c*RADIX**a * packed(node, a, a) for a, c in enumerate((1, 2, 1)))
        count = total // RADIX**33 % RADIX
        public.append(f"/-- The leaf requirements for {name}. -/\n"
                      f"abbrev {name} : Tree := s{i}\n"
                      f"theorem {name}_count : population {name} 33 = {count} := by\n"
                      f"  rw [population_of_table radix 33 s{i} t{i} h{i} (by decide)]\n"
                      "  decide +kernel\n")
    out.extend(public)
    out.append("#print axioms singleA_count\n#print axioms jointBB_count\n"
               "end ProximityGap.QuotientSignatureTables\n")
    OUTPUT.write_text("\n".join(out))
    print(f"{len(labels)} recurrence tables, {len(public)} population proofs, {OUTPUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
