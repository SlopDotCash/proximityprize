#!/usr/bin/env python3
"""Certify both extremal additive Gaussian periods on the order-16 budget-two domain.

Use Python 3.9+ without packages. For the subgroup generated by g, put
eta(b) = sum(exp(2*pi*i*b*x/p) for x in H). Since g^8 = -1 every period is real.
For its positive extremum use the eight least absolute residues of b*g^i.
For its negative extremum use 2*(b*g^i mod p)-p. In both cases the quantity
being maximized is 2*sum(cos(2*pi*v_i/m)), with m=p or m=2p, respectively.

For |v_i| <= m/2, 1-cos(2*pi*v_i/m) >= 8*v_i^2/m^2 by the chord bound for sine.
Thus a value >=16-10^-8 requires 16*10^8*sum(v_i^2) <= m^2.
The negated-period lifts are odd, and both sets of lifts lie in the same
index-p^7 lattice, whose vectors are proportional to (1,g,...,g^7) modulo p.
The eight displayed signed rotations form a basis by determinant and congruences.
Cauchy-Schwarz against the inverse-basis columns bounds every coefficient.

For survivors, E=sum(v_i^2), Q=sum(v_i^4). Taylor's inequalities
x^2/2-x^4/24 <= 1-cos(x) <= x^2/2 give the following interval:
    E/m^2 - pi^2*Q/(3*m^4) <= (16-value)/(4*pi^2) <= E/m^2.
The script uses rational arithmetic to separate the winning orbit in each sign
and to compare the two winners. Multiplying a frequency by g permutes the 16
terms of the period, so all frequencies in the winning orbit give exactly the
same algebraic number. Every discarded coefficient or frequency has
a certified reason. The frequency-zero (principal) period is excluded.
"""

from fractions import Fraction
from itertools import product
from math import gcd, isqrt


P = 680564733906249808969588989158290882561
ORIGINAL_GENERATOR = 249631592359537775319900728087975376651
G = 236023637409912314118267886612795304038
SEED = 1307463472926189116010105893757615
DEN = 10**8


def require(condition, explanation):
    if not condition:
        raise ArithmeticError(explanation)


def verify_field():
    factor = 9162596899
    require(all(factor % d != 0 for d in range(2, isqrt(factor) + 1)), "large factor composite")
    require(P - 1 == 2**92 * 3 * 5 * factor, "factorization")
    require(pow(7, P - 1, P) == 1, "Lucas root test")
    for ell in (2, 3, 5, factor):
        require(gcd(pow(7, (P - 1) // ell, P) - 1, P) == 1, "Lucas divisor test")
    require(pow(ORIGINAL_GENERATOR, 2**26, P) == G, "generator restriction")
    require(pow(G, 8, P) == P - 1, "period order")


def centered(x):
    x %= P
    return x if 2*x < P else x-P


def lattice_basis():
    seed = [centered(SEED * pow(G, i, P)) for i in range(8)]
    rows = [seed[k:] + [-x for x in seed[:k]] for k in range(8)]
    for row in rows:
        require(all((v-row[0]*pow(G, i, P)) % P == 0 for i, v in enumerate(row)),
                "basis vector outside lattice")
    return rows


def determinant_and_inverse(matrix):
    n = len(matrix)
    work = [[Fraction(x) for x in row] + [Fraction(i == j) for j in range(n)]
            for i, row in enumerate(matrix)]
    det = Fraction(1)
    for i in range(n):
        pivot = next(j for j in range(i, n) if work[j][i])
        if i != pivot:
            work[i], work[pivot] = work[pivot], work[i]
            det = -det
        scale = work[i][i]
        det *= scale
        work[i] = [x/scale for x in work[i]]
        for j in range(n):
            if j != i:
                mult = work[j][i]
                work[j] = [x - mult*y for x, y in zip(work[j], work[i])]
    return det, [row[n:] for row in work]


def arctan_enclosure(n):
    """Alternating series for arctan(1/n), with a positive next term."""
    total = sum(Fraction((-1)**k, (2*k+1)*n**(2*k+1)) for k in range(16))
    return total, total + Fraction(1, 33*n**33)


def pi_enclosure():
    # Machin's identity pi/4 = 4 arctan(1/5) - arctan(1/239).
    a, b = arctan_enclosure(5)
    c, d = arctan_enclosure(239)
    lo, hi = 16*a - 4*d, 16*b - 4*c
    require(0 < lo < hi and hi**2 < 10, "pi enclosure")
    return lo, hi


def scaled_deficit(vector, m, pi_hi):
    energy = sum(x*x for x in vector)
    fourth = sum(x**4 for x in vector)
    upper = Fraction(energy, m*m)
    return upper - pi_hi**2 * Fraction(fourth, 3*m**4), upper


def search(sign, basis, column_sq_norms, pi_hi):
    m = P if sign == 1 else 2*P
    radius_sq = Fraction(m*m, 16*DEN)
    caps = [isqrt(int(radius_sq * s)) for s in column_sq_norms]
    if sign == -1:
        # The basis is invertible mod 2 because its determinant is odd.
        # Every column has odd sum, so all-odd coordinates have all-odd coefficients.
        require(all(sum(column) % 2 == 1 for column in zip(*basis)), "parity certificate")
    ranges = [range(-c, c+1) if sign == 1 else range(1-2*((c+1)//2), c+1, 2) for c in caps]
    candidates = {}
    columns = list(zip(*basis))
    inv_two = (P+1)//2
    for coeff in product(*ranges):
        vec = tuple(sum(x*y for x, y in zip(coeff, col)) for col in columns)
        energy = sum(x*x for x in vec)
        if not energy or 16*DEN*energy > m*m:
            continue
        b = vec[0] % P if sign == 1 else vec[0]*inv_two % P
        require(b and b not in candidates, "nonzero frequency uniqueness")
        residues = [b*pow(G, i, P) % P for i in range(8)]
        expected = [centered(x) if sign == 1 else 2*x-P for x in residues]
        require(tuple(expected) == vec, "frequency reconstruction")
        candidates[b] = vec
    require(bool(candidates), "empty candidate set")
    winner = min(candidates, key=lambda b: sum(x*x for x in candidates[b]))
    orbit = {winner*pow(G, i, P) % P for i in range(16)}
    require(len(orbit) == 16 and orbit <= candidates.keys(), "incomplete winning orbit")
    winner = min(orbit)
    best = scaled_deficit(candidates[winner], m, pi_hi)
    require(4*pi_hi**2 * best[1] < Fraction(1, DEN), "winner fails search cutoff")
    for b, vec in candidates.items():
        if b not in orbit:
            require(scaled_deficit(vec, m, pi_hi)[0] > best[1], "unseparated competitor")
    print(f"sign={sign:+d} coefficients={caps} candidates={len(candidates)} "
          f"winning_frequencies={len(orbit)} smallest_frequency={winner} "
          f"energy={sum(x*x for x in candidates[winner])}")
    return best, orbit


def main():
    verify_field()
    basis = lattice_basis()
    det, inverse = determinant_and_inverse(basis)
    require(abs(det) == P**7, "lattice index")
    col_norms = [sum(x*x for x in col) for col in zip(*inverse)]
    pi_lo, pi_hi = pi_enclosure()
    pos, pos_orbit = search(1, basis, col_norms, pi_hi)
    neg, neg_orbit = search(-1, basis, col_norms, pi_hi)
    require(SEED in pos_orbit, "positive witness orbit")
    require(neg[1] < pos[0], "positive competitor crosses negative optimum")
    require(pos_orbit.isdisjoint(neg_orbit), "colliding extremal orbits")
    scale = 10**18
    floor = (16 - 4*pi_hi**2 * neg[1]) * scale
    ceiling = (16 - 4*pi_lo**2 * neg[0]) * scale
    print(f"max_abs_times_10^18 between {floor.numerator // floor.denominator} "
          f"and {-(-ceiling.numerator // ceiling.denominator)}; sign=-1")


if __name__ == "__main__":
    main()
